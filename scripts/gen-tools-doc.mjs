// Generates docs/TOOLS.md from the built server's live tool registry (run `npm run build` first).
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const home = mkdtempSync(join(tmpdir(), 'instagram-mcp-docs-'));
const transport = new StdioClientTransport({
  command: process.execPath,
  args: ['dist/cli.js', 'serve'],
  env: { ...process.env, INSTAGRAM_MCP_HOME: home, INSTAGRAM_MCP_CONFIG: '', INSTAGRAM_MCP_TEST_MODE: '1' },
  stderr: 'inherit'
});
const client = new Client({ name: 'gen-tools-doc', version: '0.0.0' });

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

function typeOf(s) {
  if (!s || typeof s !== 'object') return 'any';
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (s.const !== undefined) return JSON.stringify(s.const);
  const alt = s.anyOf ?? s.oneOf;
  if (alt) return alt.map(typeOf).join(' | ');
  if (Array.isArray(s.type)) return s.type.join(' | ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.type === 'object') return 'object';
  return s.type ?? 'any';
}

function constraints(s) {
  const c = [];
  for (const k of ['minimum', 'maximum', 'minLength', 'maxLength', 'minItems', 'maxItems', 'pattern', 'default']) {
    if (s?.[k] !== undefined) c.push(`${k}=${JSON.stringify(s[k])}`);
  }
  return c.join(', ');
}

try {
  await client.connect(transport);
  const { tools } = await client.listTools();
  const lines = [
    '# Tool reference',
    '',
    'Generated by `npm run docs:tools` from the live tool registry. Do not edit by hand. Behaviour is specified in [CONTRACT.md](CONTRACT.md).',
    '',
    `${tools.length} tools. Every tool also accepts an optional \`account\` alias unless noted.`,
    '',
    '| Tool | Read-only | Destructive | Calls Meta |',
    '|---|---|---|---|',
    ...tools.map((t) => `| [\`${t.name}\`](#${t.name}) | ${t.annotations?.readOnlyHint ?? ''} | ${t.annotations?.destructiveHint ?? ''} | ${t.annotations?.openWorldHint ?? ''} |`),
    ''
  ];
  for (const t of tools) {
    lines.push(`## ${t.name}`, '');
    if (t.title ?? t.annotations?.title) lines.push(`Title: ${t.title ?? t.annotations.title}`, '');
    const a = t.annotations ?? {};
    lines.push(`Annotations: readOnlyHint=${a.readOnlyHint}, destructiveHint=${a.destructiveHint}, idempotentHint=${a.idempotentHint}, openWorldHint=${a.openWorldHint}`, '');
    lines.push(t.description ?? '', '');
    const props = t.inputSchema?.properties ?? {};
    const req = new Set(t.inputSchema?.required ?? []);
    const names = Object.keys(props);
    if (names.length === 0) {
      lines.push('Input: none.', '');
    } else {
      lines.push('| Parameter | Type | Required | Notes |', '|---|---|---|---|');
      for (const n of names) {
        const p = props[n];
        const note = [p.description, constraints(p)].filter(Boolean).join(' ');
        lines.push(`| \`${n}\` | ${esc(typeOf(p))} | ${req.has(n) ? 'yes' : 'no'} | ${esc(note)} |`);
      }
      lines.push('');
    }
  }
  writeFileSync('docs/TOOLS.md', lines.join('\n'));
  console.log(`wrote docs/TOOLS.md (${tools.length} tools)`);
} finally {
  await client.close().catch(() => {});
  rmSync(home, { recursive: true, force: true });
}
